"""Generate safe WP-CLI ``search-replace`` commands for switching URLs to WebP."""

from __future__ import annotations

import fnmatch
import shlex
from dataclasses import dataclass
from pathlib import Path

from wp_imgopt.options import NAMING_APPEND, SOURCE_EXTENSIONS
from wp_imgopt.scanner import output_path

DEFAULT_UPLOADS_PATH = "wp-content/uploads"


@dataclass(frozen=True)
class Replacement:
    old: str
    new: str


def uploads_base_url(site_url: str, uploads_path: str = DEFAULT_UPLOADS_PATH) -> str:
    return f"{site_url.rstrip('/')}/{uploads_path.strip('/')}"


def _rel_from_entry(entry: str, base_url: str) -> str | None:
    """Accept a full URL or a path relative to the uploads folder."""
    entry = entry.strip()
    if not entry or entry.startswith("#"):
        return None
    entry = entry.split("?", 1)[0].split("#", 1)[0]
    if entry.startswith(("http://", "https://")):
        bare = base_url.split("://", 1)[-1]
        other = entry.split("://", 1)[-1]
        if not other.startswith(bare + "/"):
            return None
        return other[len(bare) + 1 :]
    return entry.lstrip("/")


def collect(
    root: Path,
    site_url: str,
    *,
    uploads_path: str = DEFAULT_UPLOADS_PATH,
    naming: str = NAMING_APPEND,
    only: tuple[str, ...] = (),
    entries: list[str] | None = None,
    fmt: str = "webp",
) -> tuple[list[Replacement], list[str]]:
    """Return (replacements, warnings). Only files whose converted twin exists qualify."""
    root = Path(root)
    base = uploads_base_url(site_url, uploads_path)
    warnings: list[str] = []
    rels: list[str] = []
    if entries is not None:
        for entry in entries:
            rel = _rel_from_entry(entry, base)
            if rel is None:
                if entry.strip() and not entry.strip().startswith("#"):
                    warnings.append(f"ignored (not under {base}): {entry.strip()}")
                continue
            rels.append(rel)
    else:
        for path in sorted(root.rglob("*")):
            if path.is_file() and path.suffix.lower() in SOURCE_EXTENSIONS:
                rels.append(path.relative_to(root).as_posix())

    replacements: list[Replacement] = []
    seen: set[str] = set()
    for rel in rels:
        if rel in seen:
            continue
        seen.add(rel)
        if Path(rel).suffix.lower() not in SOURCE_EXTENSIONS:
            warnings.append(f"ignored (not a jpg/png): {rel}")
            continue
        if only and not any(fnmatch.fnmatch(rel, pat) for pat in only):
            continue
        src = root / rel
        if not output_path(src, fmt, naming).is_file():
            warnings.append(f"skipped, no .{fmt} file on disk yet: {rel}")
            continue
        old = f"{base}/{rel}"
        new = f"{base}/{output_path(Path(rel), fmt, naming).as_posix()}"
        replacements.append(Replacement(old, new))
    replacements.sort(key=lambda r: (-len(r.old), r.old))
    return replacements, warnings


def _escape_slashes(value: str) -> str:
    """Elementor stores URLs inside JSON, so every slash is written as \\/."""
    return value.replace("/", "\\/")


def _command(rep: Replacement, wp_path: str | None, dry_run: bool) -> str:
    parts = ["wp", "search-replace", rep.old, rep.new]
    if wp_path:
        parts.append(f"--path={wp_path}")
    parts += ["--skip-columns=guid", "--precise", "--report-changed-only"]
    if dry_run:
        parts.append("--dry-run")
    return " ".join(shlex.quote(p) for p in parts)


def render(
    replacements: list[Replacement],
    *,
    elementor: bool = False,
    wp_path: str | None = None,
) -> list[str]:
    """Produce an ordered, copy-pasteable list of shell lines (comments start with #)."""
    reps = list(replacements)
    if elementor:
        reps += [Replacement(_escape_slashes(r.old), _escape_slashes(r.new)) for r in replacements]
    out = [
        "# Generated by wp-imgopt --sql-replace. Review before running.",
        "# Run each block ONCE: re-running would turn .webp into .webp.webp.",
        "",
        "# 1. Back up the database",
        "wp db export"
        + (f" --path={shlex.quote(wp_path)}" if wp_path else "")
        + " before-webp-switch.sql",
        "",
        "# 2. Dry run (nothing is written)",
    ]
    out += [_command(r, wp_path, True) for r in reps]
    out += ["", "# 3. Apply"]
    out += [_command(r, wp_path, False) for r in reps]
    out += ["", "# 4. Flush caches"]
    suffix = f" --path={shlex.quote(wp_path)}" if wp_path else ""
    if elementor:
        out.append("wp elementor flush-css" + suffix)
    out.append("wp cache flush" + suffix)
    return out
